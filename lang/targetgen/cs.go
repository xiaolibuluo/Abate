// csGen renders the C# target: one target.cs of top-level statements whose
// tests assert through a Check helper throwing on failure; running the file
// with dotnet is the self-check.
type csGen struct{}

func (csGen) fileName() string { return "target.cs" }

func (csGen) header() string {
	return "// Code generated by abate targetgen. DO NOT EDIT.\n" +
		"// Deterministic C# mutation-testing target.\n" +
		"using System;\n\n" +
		"static void Check(bool cond)\n" +
		"{\n" +
		"    if (!cond)\n" +
		"    {\n" +
		"        throw new Exception(\"targetgen assertion failed\");\n" +
		"    }\n" +
		"}\n"
}

func (csGen) footer(testNames []string) string {
	var sb strings.Builder
	sb.WriteString("\n")
	for _, name := range testNames {
		fmt.Fprintf(&sb, "%s();\n", name)
	}
	sb.WriteString("Console.WriteLine(\"CSTARGET_OK\");\n")
	return sb.String()
}

func (g csGen) build(stream *rand.Stream, name, structure, level string) scriptBody {
	switch structure {
	case "arith":
		return csArith(stream, name, level)
	case "boundary":
		return csBoundary(stream, name, level)
	case "constant":
		return csConstant(stream, name, level)
	case "controlflow":
		return csControlFlow(stream, name, level)
	case "returnvalue":
		return csReturnValue(stream, name, level)
	case "negate":
		return csNegate(stream, name, level)
	case "callremove":
		return csCallRemove(stream, name, level)
	}
	panic("targetgen: unknown cs structure " + structure)
}

func (g csGen) buildMixed(stream *rand.Stream, name, primary, secondary, level string) scriptBody {
	a := intOperand(stream)
	b := intOperand(stream)
	limit := intOperand(stream)
	x := intOperand(stream)
	y := intOperand(stream)
	edge := pinned(stream, level)
	verdict := csBool(x*a+y*b < limit)
	src := fmt.Sprintf(`
bool %s(int x, int y)
{
    // Scale x by %d and y by %d, then compare the sum against %d.
    int total = x * %d + y * %d;
    return total < %d;
}
`, name, a, b, limit, a, b, limit)
	var edgeCase string
	if edge {
		edgeCase = fmt.Sprintf("Check(%s(%d, 0) == %s);\n", name, limit/a, csBool((limit/a)*a < limit))
	}
	test := fmt.Sprintf(`
void test_%s()
{
    Check(%s(%d, %d) == %s);
    %s}
`, name, name, x, y, verdict, edgeCase)
	return scriptBody{source: src, test: test, pinned: edge}
}

// csBool renders a Go boolean as C# source.
func csBool(v bool) string {
	if v {
		return "true"
	}
	return "false"
}

func csArith(stream *rand.Stream, name, level string) scriptBody {
	a := intOperand(stream)
	b := intOperand(stream)
	x := intOperand(stream)
	y := intOperand(stream)
	edge := pinned(stream, level)
	src := fmt.Sprintf(`
int %s(int x, int y)
{
    return x * %d + y * %d;
}
`, name, a, b)
	var edgeCase string
	if edge {
		edgeCase = fmt.Sprintf("    Check(%s(0, 1) == %d);\n", name, b)
	}
	test := fmt.Sprintf(`
void test_%s()
{
    Check(%s(%d, %d) == %d);
%s}
`, name, name, x, y, x*a+y*b, edgeCase)
	return scriptBody{source: src, test: test, pinned: edge}
}

func csBoundary(stream *rand.Stream, name, level string) scriptBody {
	limit := intOperand(stream)
	below := 1 + stream.IntN(limit-1)
	above := limit + intOperand(stream)
	edge := pinned(stream, level)
	src := fmt.Sprintf(`
bool %s(int n)
{
    return n < %d;
}
`, name, limit)
	var edgeCase string
	if edge {
		edgeCase = fmt.Sprintf("    Check(!%s(%d));\n", name, limit)
	}
	test := fmt.Sprintf(`
void test_%s()
{
    Check(%s(%d));
    Check(!%s(%d));
%s}
`, name, name, below, name, above, edgeCase)
	return scriptBody{source: src, test: test, pinned: edge}
}

func csConstant(stream *rand.Stream, name, level string) scriptBody {
	base := intOperand(stream)
	factor := intOperand(stream)
	offset := intOperand(stream)
	edge := pinned(stream, level)
	src := fmt.Sprintf(`
int %s()
{
    int @base = %d;
    return @base * %d + %d;
}
`, name, base, factor, offset)
	var edgeCase string
	if edge {
		edgeCase = fmt.Sprintf("    Check(%s() != 0);\n", name)
	}
	test := fmt.Sprintf(`
void test_%s()
{
    Check(%s() == %d);
%s}
`, name, name, base*factor+offset, edgeCase)
	return scriptBody{source: src, test: test, pinned: edge}
}

func csControlFlow(stream *rand.Stream, name, level string) scriptBody {
	stop := 3 + stream.IntN(9)
	skip := 1 + stream.IntN(stop-1)
	edge := pinned(stream, level)
	src := fmt.Sprintf(`
int %s()
{
    int total = 0;
    for (int i = 0; i < %d; i++)
    {
        if (i == %d)
        {
            continue;
        }
        if (total > %d * %d)
        {
            break;
        }
        total += i;
    }
    return total;
}
`, name, stop, skip, stop, skip)
	want := 0
	for i := 0; i < stop; i++ {
		if i == skip {
			continue
		}
		if want > stop*skip {
			break
		}
		want += i
	}
	var edgeCase string
	if edge {
		edgeCase = fmt.Sprintf("    Check(%s() >= 0);\n", name)
	}
	test := fmt.Sprintf(`
void test_%s()
{
    Check(%s() == %d);
%s}
`, name, name, want, edgeCase)
	return scriptBody{source: src, test: test, pinned: edge}
}

func csReturnValue(stream *rand.Stream, name, level string) scriptBody {
	threshold := intOperand(stream)
	high := threshold + intOperand(stream)
	edge := pinned(stream, level)
	src := fmt.Sprintf(`
bool %s(int n)
{
    if (n >= %d)
    {
        return true;
    }
    return false;
}
`, name, threshold)
	var edgeCase string
	if edge {
		low := intOperand(stream) % threshold
		edgeCase = fmt.Sprintf("    Check(!%s(%d));\n", name, low)
	}
	test := fmt.Sprintf(`
void test_%s()
{
    Check(%s(%d));
%s}
`, name, name, high, edgeCase)
	return scriptBody{source: src, test: test, pinned: edge}
}

func csNegate(stream *rand.Stream, name, level string) scriptBody {
	want := intOperand(stream)
	miss := want + 1 + stream.IntN(5)
	edge := pinned(stream, level)
	src := fmt.Sprintf(`
bool %s(int n)
{
    return n == %d;
}
`, name, want)
	var edgeCase string
	if edge {
		edgeCase = fmt.Sprintf("    Check(!%s(%d));\n", name, miss)
	}
	test := fmt.Sprintf(`
void test_%s()
{
    Check(%s(%d));
%s}
`, name, name, want, edgeCase)
	return scriptBody{source: src, test: test, pinned: edge}
}

func csCallRemove(stream *rand.Stream, name, level string) scriptBody {
	base := intOperand(stream)
	input := intOperand(stream)
	edge := pinned(stream, level)
	helper := name + "_add"
	src := fmt.Sprintf(`
int %s(int n)
{
    return n + %d;
}

int %s(int n)
{
    return %s(n);
}
`, helper, base, name, helper)
	var edgeCase string
	if edge {
		edgeCase = fmt.Sprintf("    Check(%s(0) == %d);\n", name, base)
	}
	test := fmt.Sprintf(`
void test_%s()
{
    Check(%s(%d) == %d);
%s}
`, name, name, input, input+base, edgeCase)
	return scriptBody{source: src, test: test, pinned: edge}
}
