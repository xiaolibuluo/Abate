package targetgen

import (
	"fmt"
	"strings"

	"abate/sim/rand"
)

// cGen renders the C target: one target.c whose tests assert through the
// standard assert macro; compiling and running the file is the self-check.
type cGen struct{}

func (cGen) fileName() string { return "target.c" }

func (cGen) header() string {
	return "/* Code generated by abate targetgen. DO NOT EDIT. */\n" +
		"/* Deterministic C mutation-testing target. */\n" +
		"#include <assert.h>\n" +
		"#include <stdbool.h>\n" +
		"#include <stdio.h>\n"
}

func (cGen) footer(testNames []string) string {
	var sb strings.Builder
	sb.WriteString("\nint main(void) {\n")
	for _, name := range testNames {
		fmt.Fprintf(&sb, "  %s();\n", name)
	}
	sb.WriteString("  puts(\"CTARGET_OK\");\n")
	sb.WriteString("  return 0;\n}\n")
	return sb.String()
}

func (g cGen) build(stream *rand.Stream, name, structure, level string) scriptBody {
	switch structure {
	case "arith":
		return cArith(stream, name, level)
	case "boundary":
		return cBoundary(stream, name, level)
	case "constant":
		return cConstant(stream, name, level)
	case "controlflow":
		return cControlFlow(stream, name, level)
	case "returnvalue":
		return cReturnValue(stream, name, level)
	case "negate":
		return cNegate(stream, name, level)
	case "callremove":
		return cCallRemove(stream, name, level)
	}
	panic("targetgen: unknown c structure " + structure)
}

func (g cGen) buildMixed(stream *rand.Stream, name, primary, secondary, level string) scriptBody {
	a := intOperand(stream)
	b := intOperand(stream)
	limit := intOperand(stream)
	x := intOperand(stream)
	y := intOperand(stream)
	edge := pinned(stream, level)
	verdict := x*a+y*b < limit
	src := fmt.Sprintf(`
bool %s(int x, int y) {
  /* Scale x by %d and y by %d, then compare the sum against %d. */
  const int total = x * %d + y * %d;
  return total < %d;
}
`, name, a, b, limit, a, b, limit)
	var edgeCase string
	if edge {
		edgeCase = fmt.Sprintf("  %s\n", cAssertBool(fmt.Sprintf("%s(%d, 0)", name, limit/a), (limit/a)*a < limit))
	}
	test := fmt.Sprintf(`
void test_%s(void) {
  %s
%s}`, name, cAssertBool(fmt.Sprintf("%s(%d, %d)", name, x, y), verdict), edgeCase)
	return scriptBody{source: src, test: test, pinned: edge}
}

// cAssertBool renders one assert statement checking the truth value of expr.
func cAssertBool(expr string, want bool) string {
	if want {
		return "assert(" + expr + ");"
	}
	return "assert(!(" + expr + "));"
}

func cArith(stream *rand.Stream, name, level string) scriptBody {
	a := intOperand(stream)
	b := intOperand(stream)
	x := intOperand(stream)
	y := intOperand(stream)
	edge := pinned(stream, level)
	src := fmt.Sprintf(`
int %s(int x, int y) {
  return x * %d + y * %d;
}
`, name, a, b)
	var edgeCase string
	if edge {
		edgeCase = fmt.Sprintf("  assert(%s(0, 1) == %d);\n", name, b)
	}
	test := fmt.Sprintf(`
void test_%s(void) {
  assert(%s(%d, %d) == %d);
%s}`, name, name, x, y, x*a+y*b, edgeCase)
	return scriptBody{source: src, test: test, pinned: edge}
}

func cBoundary(stream *rand.Stream, name, level string) scriptBody {
	limit := intOperand(stream)
	below := 1 + stream.IntN(limit-1)
	above := limit + intOperand(stream)
	edge := pinned(stream, level)
	src := fmt.Sprintf(`
bool %s(int n) {
  return n < %d;
}
`, name, limit)
	var edgeCase string
	if edge {
		edgeCase = fmt.Sprintf("  assert(!%s(%d));\n", name, limit)
	}
	test := fmt.Sprintf(`
void test_%s(void) {
  assert(%s(%d));
  assert(!%s(%d));
%s}`, name, name, below, name, above, edgeCase)
	return scriptBody{source: src, test: test, pinned: edge}
}

func cConstant(stream *rand.Stream, name, level string) scriptBody {
	base := intOperand(stream)
	factor := intOperand(stream)
	offset := intOperand(stream)
	edge := pinned(stream, level)
	src := fmt.Sprintf(`
int %s(void) {
  const int base = %d;
  return base * %d + %d;
}
`, name, base, factor, offset)
	var edgeCase string
	if edge {
		edgeCase = fmt.Sprintf("  assert(%s() != 0);\n", name)
	}
	test := fmt.Sprintf(`
void test_%s(void) {
  assert(%s() == %d);
%s}`, name, name, base*factor+offset, edgeCase)
	return scriptBody{source: src, test: test, pinned: edge}
}

func cControlFlow(stream *rand.Stream, name, level string) scriptBody {
	stop := 3 + stream.IntN(9)
	skip := 1 + stream.IntN(stop-1)
	edge := pinned(stream, level)
	src := fmt.Sprintf(`
int %s(void) {
  int total = 0;
  for (int i = 0; i < %d; i++) {
    if (i == %d) {
      continue;
    }
    if (total > %d * %d) {
      break;
    }
    total += i;
  }
  return total;
}
`, name, stop, skip, stop, skip)
	want := 0
	for i := 0; i < stop; i++ {
		if i == skip {
			continue
		}
		if want > stop*skip {
			break
		}
		want += i
	}
	var edgeCase string
	if edge {
		edgeCase = fmt.Sprintf("  assert(%s() >= 0);\n", name)
	}
	test := fmt.Sprintf(`
void test_%s(void) {
  assert(%s() == %d);
%s}`, name, name, want, edgeCase)
	return scriptBody{source: src, test: test, pinned: edge}
}

func cReturnValue(stream *rand.Stream, name, level string) scriptBody {
	threshold := intOperand(stream)
	high := threshold + intOperand(stream)
	edge := pinned(stream, level)
	src := fmt.Sprintf(`
bool %s(int n) {
  if (n >= %d) {
    return true;
  }
  return false;
}
`, name, threshold)
	var edgeCase string
	if edge {
		low := intOperand(stream) % threshold
		edgeCase = fmt.Sprintf("  assert(!%s(%d));\n", name, low)
	}
	test := fmt.Sprintf(`
void test_%s(void) {
  assert(%s(%d));
%s}`, name, name, high, edgeCase)
	return scriptBody{source: src, test: test, pinned: edge}
}

func cNegate(stream *rand.Stream, name, level string) scriptBody {
	want := intOperand(stream)
	miss := want + 1 + stream.IntN(5)
	edge := pinned(stream, level)
	src := fmt.Sprintf(`
bool %s(int n) {
  return n == %d;
}
`, name, want)
	var edgeCase string
	if edge {
		edgeCase = fmt.Sprintf("  assert(!%s(%d));\n", name, miss)
	}
	test := fmt.Sprintf(`
void test_%s(void) {
  assert(%s(%d));
%s}`, name, name, want, edgeCase)
	return scriptBody{source: src, test: test, pinned: edge}
}

func cCallRemove(stream *rand.Stream, name, level string) scriptBody {
	base := intOperand(stream)
	input := intOperand(stream)
	edge := pinned(stream, level)
	helper := name + "_add"
	src := fmt.Sprintf(`
static int %s(int n) {
  return n + %d;
}

int %s(int n) {
  return %s(n);
}
`, helper, base, name, helper)
	var edgeCase string
	if edge {
		edgeCase = fmt.Sprintf("  assert(%s(0) == %d);\n", name, base)
	}
	test := fmt.Sprintf(`
void test_%s(void) {
  assert(%s(%d) == %d);
%s}`, name, name, input, input+base, edgeCase)
	return scriptBody{source: src, test: test, pinned: edge}
}
