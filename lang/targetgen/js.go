// jsGen renders the JavaScript target: one target.js executed by Node,
// whose tests assert through the built-in node:assert module, so running
// the file with node is the self-check.
type jsGen struct{}

func (jsGen) fileName() string { return "target.js" }

func (jsGen) header() string {
	return "// Code generated by abate targetgen. DO NOT EDIT.\n" +
		"// Deterministic JavaScript mutation-testing target.\n" +
		"\"use strict\";\n" +
		"const assert = require(\"node:assert\");\n"
}

func (jsGen) footer(testNames []string) string {
	var sb strings.Builder
	sb.WriteString("\nfunction main() {\n")
	for _, name := range testNames {
		fmt.Fprintf(&sb, "  %s();\n", name)
	}
	sb.WriteString("  console.log(\"JSTARGET_OK\");\n}\n\nmain();\n")
	return sb.String()
}

func (g jsGen) build(stream *rand.Stream, name, structure, level string) scriptBody {
	switch structure {
	case "arith":
		return jsArith(stream, name, level)
	case "boundary":
		return jsBoundary(stream, name, level)
	case "constant":
		return jsConstant(stream, name, level)
	case "controlflow":
		return jsControlFlow(stream, name, level)
	case "returnvalue":
		return jsReturnValue(stream, name, level)
	case "negate":
		return jsNegate(stream, name, level)
	case "callremove":
		return jsCallRemove(stream, name, level)
	}
	panic("targetgen: unknown js structure " + structure)
}

func (g jsGen) buildMixed(stream *rand.Stream, name, primary, secondary, level string) scriptBody {
	a := intOperand(stream)
	b := intOperand(stream)
	limit := intOperand(stream)
	x := intOperand(stream)
	y := intOperand(stream)
	edge := pinned(stream, level)
	verdict := jsBool(x*a+y*b < limit)
	src := fmt.Sprintf(`
function %s(x, y) {
  // Scale x by %d and y by %d, then compare the sum against %d.
  const total = x * %d + y * %d;
  return total < %d;
}
`, name, a, b, limit, a, b, limit)
	var edgeCase string
	if edge {
		edgeCase = fmt.Sprintf("  assert.strictEqual(%s(%d, 0), %s);\n", name, limit/a, jsBool((limit/a)*a < limit))
	}
	test := fmt.Sprintf(`
function test_%s() {
  assert.strictEqual(%s(%d, %d), %s);
%s}`, name, name, x, y, verdict, edgeCase)
	return scriptBody{source: src, test: test, pinned: edge}
}

// jsBool renders a Go boolean as JavaScript source.
func jsBool(v bool) string {
	if v {
		return "true"
	}
	return "false"
}

func jsArith(stream *rand.Stream, name, level string) scriptBody {
	a := intOperand(stream)
	b := intOperand(stream)
	x := intOperand(stream)
	y := intOperand(stream)
	edge := pinned(stream, level)
	src := fmt.Sprintf(`
function %s(x, y) {
  return x * %d + y * %d;
}
`, name, a, b)
	var edgeCase string
	if edge {
		edgeCase = fmt.Sprintf("  assert.strictEqual(%s(0, 1), %d);\n", name, b)
	}
	test := fmt.Sprintf(`
function test_%s() {
  assert.strictEqual(%s(%d, %d), %d);
%s}`, name, name, x, y, x*a+y*b, edgeCase)
	return scriptBody{source: src, test: test, pinned: edge}
}

func jsBoundary(stream *rand.Stream, name, level string) scriptBody {
	limit := intOperand(stream)
	below := 1 + stream.IntN(limit-1)
	above := limit + intOperand(stream)
	edge := pinned(stream, level)
	src := fmt.Sprintf(`
function %s(n) {
  return n < %d;
}
`, name, limit)
	var edgeCase string
	if edge {
		edgeCase = fmt.Sprintf("  assert.strictEqual(%s(%d), false);\n", name, limit)
	}
	test := fmt.Sprintf(`
function test_%s() {
  assert.strictEqual(%s(%d), true);
  assert.strictEqual(%s(%d), false);
%s}`, name, name, below, name, above, edgeCase)
	return scriptBody{source: src, test: test, pinned: edge}
}

func jsConstant(stream *rand.Stream, name, level string) scriptBody {
	base := intOperand(stream)
	factor := intOperand(stream)
	offset := intOperand(stream)
	edge := pinned(stream, level)
	src := fmt.Sprintf(`
function %s() {
  const base = %d;
  return base * %d + %d;
}
`, name, base, factor, offset)
	var edgeCase string
	if edge {
		edgeCase = fmt.Sprintf("  assert.notStrictEqual(%s(), 0);\n", name)
	}
	test := fmt.Sprintf(`
function test_%s() {
  assert.strictEqual(%s(), %d);
%s}`, name, name, base*factor+offset, edgeCase)
	return scriptBody{source: src, test: test, pinned: edge}
}

func jsControlFlow(stream *rand.Stream, name, level string) scriptBody {
	stop := 3 + stream.IntN(9)
	skip := 1 + stream.IntN(stop-1)
	edge := pinned(stream, level)
	src := fmt.Sprintf(`
function %s() {
  let total = 0;
  for (let i = 0; i < %d; i++) {
    if (i === %d) {
      continue;
    }
    if (total > %d * %d) {
      break;
    }
    total += i;
  }
  return total;
}
`, name, stop, skip, stop, skip)
	want := 0
	for i := 0; i < stop; i++ {
		if i == skip {
			continue
		}
		if want > stop*skip {
			break
		}
		want += i
	}
	var edgeCase string
	if edge {
		edgeCase = fmt.Sprintf("  assert.ok(%s() >= 0);\n", name)
	}
	test := fmt.Sprintf(`
function test_%s() {
  assert.strictEqual(%s(), %d);
%s}`, name, name, want, edgeCase)
	return scriptBody{source: src, test: test, pinned: edge}
}

func jsReturnValue(stream *rand.Stream, name, level string) scriptBody {
	threshold := intOperand(stream)
	high := threshold + intOperand(stream)
	edge := pinned(stream, level)
	src := fmt.Sprintf(`
function %s(n) {
  if (n >= %d) {
    return true;
  }
  return false;
}
`, name, threshold)
	var edgeCase string
	if edge {
		low := intOperand(stream) % threshold
		edgeCase = fmt.Sprintf("  assert.strictEqual(%s(%d), false);\n", name, low)
	}
	test := fmt.Sprintf(`
function test_%s() {
  assert.strictEqual(%s(%d), true);
%s}`, name, name, high, edgeCase)
	return scriptBody{source: src, test: test, pinned: edge}
}

func jsNegate(stream *rand.Stream, name, level string) scriptBody {
	want := intOperand(stream)
	miss := want + 1 + stream.IntN(5)
	edge := pinned(stream, level)
	src := fmt.Sprintf(`
function %s(n) {
  return n === %d;
}
`, name, want)
	var edgeCase string
	if edge {
		edgeCase = fmt.Sprintf("  assert.strictEqual(%s(%d), false);\n", name, miss)
	}
	test := fmt.Sprintf(`
function test_%s() {
  assert.strictEqual(%s(%d), true);
%s}`, name, name, want, edgeCase)
	return scriptBody{source: src, test: test, pinned: edge}
}

func jsCallRemove(stream *rand.Stream, name, level string) scriptBody {
	base := intOperand(stream)
	input := intOperand(stream)
	edge := pinned(stream, level)
	helper := name + "_add"
	src := fmt.Sprintf(`
function %s(n) {
  return %s(n);
}

function %s(n) {
  return n + %d;
}
`, name, helper, helper, base)
	var edgeCase string
	if edge {
		edgeCase = fmt.Sprintf("  assert.strictEqual(%s(0), %d);\n", name, base)
	}
	test := fmt.Sprintf(`
function test_%s() {
  assert.strictEqual(%s(%d), %d);
%s}`, name, name, input, input+base, edgeCase)
	return scriptBody{source: src, test: test, pinned: edge}
}
