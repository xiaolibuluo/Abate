package targetgen

import (
	"fmt"
	"strings"

	"abate/sim/rand"
)

// ktGen renders the Kotlin target: one target.kt whose tests assert through
// the standard check function; compiling with kotlinc and running the jar
// is the self-check.
type ktGen struct{}

func (ktGen) fileName() string { return "target.kt" }

func (ktGen) header() string {
	return "// Code generated by abate targetgen. DO NOT EDIT.\n" +
		"// Deterministic Kotlin mutation-testing target.\n"
}

func (ktGen) footer(testNames []string) string {
	var sb strings.Builder
	sb.WriteString("\nfun main() {\n")
	for _, name := range testNames {
		fmt.Fprintf(&sb, "    %s()\n", name)
	}
	sb.WriteString("    println(\"KTTARGET_OK\")\n}\n")
	return sb.String()
}

func (g ktGen) build(stream *rand.Stream, name, structure, level string) scriptBody {
	switch structure {
	case "arith":
		return ktArith(stream, name, level)
	case "boundary":
		return ktBoundary(stream, name, level)
	case "constant":
		return ktConstant(stream, name, level)
	case "controlflow":
		return ktControlFlow(stream, name, level)
	case "returnvalue":
		return ktReturnValue(stream, name, level)
	case "negate":
		return ktNegate(stream, name, level)
	case "callremove":
		return ktCallRemove(stream, name, level)
	}
	panic("targetgen: unknown kt structure " + structure)
}

func (g ktGen) buildMixed(stream *rand.Stream, name, primary, secondary, level string) scriptBody {
	a := intOperand(stream)
	b := intOperand(stream)
	limit := intOperand(stream)
	x := intOperand(stream)
	y := intOperand(stream)
	edge := pinned(stream, level)
	verdict := ktBool(x*a+y*b < limit)
	src := fmt.Sprintf(`
fun %s(x: Long, y: Long): Boolean {
    // Scale x by %d and y by %d, then compare the sum against %d.
    val total = x * %d + y * %d
    return total < %d
}
`, name, a, b, limit, a, b, limit)
	var edgeCase string
	if edge {
		edgeCase = fmt.Sprintf("    check(%s(%dL, 0L) == %s)\n", name, limit/a, ktBool((limit/a)*a < limit))
	}
	test := fmt.Sprintf(`
fun test_%s() {
    check(%s(%dL, %dL) == %s)
%s}`, name, name, x, y, verdict, edgeCase)
	return scriptBody{source: src, test: test, pinned: edge}
}

// ktBool renders a Go boolean as Kotlin source.
func ktBool(v bool) string {
	if v {
		return "true"
	}
	return "false"
}

func ktArith(stream *rand.Stream, name, level string) scriptBody {
	a := intOperand(stream)
	b := intOperand(stream)
	x := intOperand(stream)
	y := intOperand(stream)
	edge := pinned(stream, level)
	src := fmt.Sprintf(`
fun %s(x: Long, y: Long): Long {
    return x * %d + y * %d
}
`, name, a, b)
	var edgeCase string
	if edge {
		edgeCase = fmt.Sprintf("    check(%s(0L, 1L) == %dL)\n", name, b)
	}
	test := fmt.Sprintf(`
fun test_%s() {
    check(%s(%dL, %dL) == %dL)
%s}`, name, name, x, y, x*a+y*b, edgeCase)
	return scriptBody{source: src, test: test, pinned: edge}
}

func ktBoundary(stream *rand.Stream, name, level string) scriptBody {
	limit := intOperand(stream)
	below := 1 + stream.IntN(limit-1)
	above := limit + intOperand(stream)
	edge := pinned(stream, level)
	src := fmt.Sprintf(`
fun %s(n: Long): Boolean {
    return n < %d
}
`, name, limit)
	var edgeCase string
	if edge {
		edgeCase = fmt.Sprintf("    check(!%s(%dL))\n", name, limit)
	}
	test := fmt.Sprintf(`
fun test_%s() {
    check(%s(%dL))
    check(!%s(%dL))
%s}`, name, name, below, name, above, edgeCase)
	return scriptBody{source: src, test: test, pinned: edge}
}

func ktConstant(stream *rand.Stream, name, level string) scriptBody {
	base := intOperand(stream)
	factor := intOperand(stream)
	offset := intOperand(stream)
	edge := pinned(stream, level)
	src := fmt.Sprintf(`
fun %s(): Long {
    val base = %dL
    return base * %d + %d
}
`, name, base, factor, offset)
	var edgeCase string
	if edge {
		edgeCase = fmt.Sprintf("    check(%s() != 0L)\n", name)
	}
	test := fmt.Sprintf(`
fun test_%s() {
    check(%s() == %dL)
%s}`, name, name, base*factor+offset, edgeCase)
	return scriptBody{source: src, test: test, pinned: edge}
}

func ktControlFlow(stream *rand.Stream, name, level string) scriptBody {
	stop := 3 + stream.IntN(9)
	skip := 1 + stream.IntN(stop-1)
	edge := pinned(stream, level)
	src := fmt.Sprintf(`
fun %s(): Long {
    var total = 0L
    for (i in 0 until %d) {
        if (i == %d) {
            continue
        }
        if (total > %dL * %dL) {
            break
        }
        total += i
    }
    return total
}
`, name, stop, skip, stop, skip)
	want := 0
	for i := 0; i < stop; i++ {
		if i == skip {
			continue
		}
		if want > stop*skip {
			break
		}
		want += i
	}
	var edgeCase string
	if edge {
		edgeCase = fmt.Sprintf("    check(%s() >= 0L)\n", name)
	}
	test := fmt.Sprintf(`
fun test_%s() {
    check(%s() == %dL)
%s}`, name, name, want, edgeCase)
	return scriptBody{source: src, test: test, pinned: edge}
}

func ktReturnValue(stream *rand.Stream, name, level string) scriptBody {
	threshold := intOperand(stream)
	high := threshold + intOperand(stream)
	edge := pinned(stream, level)
	src := fmt.Sprintf(`
fun %s(n: Long): Boolean {
    if (n >= %d) {
        return true
    }
    return false
}
`, name, threshold)
	var edgeCase string
	if edge {
		low := intOperand(stream) % threshold
		edgeCase = fmt.Sprintf("    check(!%s(%dL))\n", name, low)
	}
	test := fmt.Sprintf(`
fun test_%s() {
    check(%s(%dL))
%s}`, name, name, high, edgeCase)
	return scriptBody{source: src, test: test, pinned: edge}
}

func ktNegate(stream *rand.Stream, name, level string) scriptBody {
	want := intOperand(stream)
	miss := want + 1 + stream.IntN(5)
	edge := pinned(stream, level)
	src := fmt.Sprintf(`
fun %s(n: Long): Boolean {
    return n == %dL
}
`, name, want)
	var edgeCase string
	if edge {
		edgeCase = fmt.Sprintf("    check(!%s(%dL))\n", name, miss)
	}
	test := fmt.Sprintf(`
fun test_%s() {
    check(%s(%dL))
%s}`, name, name, want, edgeCase)
	return scriptBody{source: src, test: test, pinned: edge}
}

func ktCallRemove(stream *rand.Stream, name, level string) scriptBody {
	base := intOperand(stream)
	input := intOperand(stream)
	edge := pinned(stream, level)
	helper := name + "_add"
	src := fmt.Sprintf(`
fun %s(n: Long): Long {
    return n + %d
}

fun %s(n: Long): Long {
    return %s(n)
}
`, helper, base, name, helper)
	var edgeCase string
	if edge {
		edgeCase = fmt.Sprintf("    check(%s(0L) == %dL)\n", name, base)
	}
	test := fmt.Sprintf(`
fun test_%s() {
    check(%s(%dL) == %dL)
%s}`, name, name, input, input+base, edgeCase)
	return scriptBody{source: src, test: test, pinned: edge}
}
