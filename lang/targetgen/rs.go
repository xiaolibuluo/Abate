package targetgen

import (
	"fmt"
	"strings"

	"abate/sim/rand"
)

// rsGen renders the Rust target: one target.rs whose tests assert through
// the standard assert macros; compiling with rustc and running the binary
// is the self-check.
type rsGen struct{}

func (rsGen) fileName() string { return "target.rs" }

func (rsGen) header() string {
	return "// Code generated by abate targetgen. DO NOT EDIT.\n" +
		"// Deterministic Rust mutation-testing target.\n" +
		"#![allow(dead_code)]\n"
}

func (rsGen) footer(testNames []string) string {
	var sb strings.Builder
	sb.WriteString("\nfn main() {\n")
	for _, name := range testNames {
		fmt.Fprintf(&sb, "    %s();\n", name)
	}
	sb.WriteString("    println!(\"RSTARGET_OK\");\n}\n")
	return sb.String()
}

func (g rsGen) build(stream *rand.Stream, name, structure, level string) scriptBody {
	switch structure {
	case "arith":
		return rsArith(stream, name, level)
	case "boundary":
		return rsBoundary(stream, name, level)
	case "constant":
		return rsConstant(stream, name, level)
	case "controlflow":
		return rsControlFlow(stream, name, level)
	case "returnvalue":
		return rsReturnValue(stream, name, level)
	case "negate":
		return rsNegate(stream, name, level)
	case "callremove":
		return rsCallRemove(stream, name, level)
	}
	panic("targetgen: unknown rs structure " + structure)
}

func (g rsGen) buildMixed(stream *rand.Stream, name, primary, secondary, level string) scriptBody {
	a := intOperand(stream)
	b := intOperand(stream)
	limit := intOperand(stream)
	x := intOperand(stream)
	y := intOperand(stream)
	edge := pinned(stream, level)
	verdict := rsBool(x*a+y*b < limit)
	src := fmt.Sprintf(`
fn %s(x: i64, y: i64) -> bool {
    // Scale x by %d and y by %d, then compare the sum against %d.
    let total = x * %d + y * %d;
    total < %d
}
`, name, a, b, limit, a, b, limit)
	var edgeCase string
	if edge {
		edgeCase = fmt.Sprintf("    assert_eq!(%s(%d, 0), %s);\n", name, limit/a, rsBool((limit/a)*a < limit))
	}
	test := fmt.Sprintf(`
fn test_%s() {
    assert_eq!(%s(%d, %d), %s);
%s}`, name, name, x, y, verdict, edgeCase)
	return scriptBody{source: src, test: test, pinned: edge}
}

// rsBool renders a Go boolean as Rust source.
func rsBool(v bool) string {
	if v {
		return "true"
	}
	return "false"
}

func rsArith(stream *rand.Stream, name, level string) scriptBody {
	a := intOperand(stream)
	b := intOperand(stream)
	x := intOperand(stream)
	y := intOperand(stream)
	edge := pinned(stream, level)
	src := fmt.Sprintf(`
fn %s(x: i64, y: i64) -> i64 {
    x * %d + y * %d
}
`, name, a, b)
	var edgeCase string
	if edge {
		edgeCase = fmt.Sprintf("    assert_eq!(%s(0, 1), %d);\n", name, b)
	}
	test := fmt.Sprintf(`
fn test_%s() {
    assert_eq!(%s(%d, %d), %d);
%s}`, name, name, x, y, x*a+y*b, edgeCase)
	return scriptBody{source: src, test: test, pinned: edge}
}

func rsBoundary(stream *rand.Stream, name, level string) scriptBody {
	limit := intOperand(stream)
	below := 1 + stream.IntN(limit-1)
	above := limit + intOperand(stream)
	edge := pinned(stream, level)
	src := fmt.Sprintf(`
fn %s(n: i64) -> bool {
    n < %d
}
`, name, limit)
	var edgeCase string
	if edge {
		edgeCase = fmt.Sprintf("    assert!(!%s(%d));\n", name, limit)
	}
	test := fmt.Sprintf(`
fn test_%s() {
    assert!(%s(%d));
    assert!(!%s(%d));
%s}`, name, name, below, name, above, edgeCase)
	return scriptBody{source: src, test: test, pinned: edge}
}

func rsConstant(stream *rand.Stream, name, level string) scriptBody {
	base := intOperand(stream)
	factor := intOperand(stream)
	offset := intOperand(stream)
	edge := pinned(stream, level)
	src := fmt.Sprintf(`
fn %s() -> i64 {
    let base = %d;
    base * %d + %d
}
`, name, base, factor, offset)
	var edgeCase string
	if edge {
		edgeCase = fmt.Sprintf("    assert_ne!(%s(), 0);\n", name)
	}
	test := fmt.Sprintf(`
fn test_%s() {
    assert_eq!(%s(), %d);
%s}`, name, name, base*factor+offset, edgeCase)
	return scriptBody{source: src, test: test, pinned: edge}
}

func rsControlFlow(stream *rand.Stream, name, level string) scriptBody {
	stop := 3 + stream.IntN(9)
	skip := 1 + stream.IntN(stop-1)
	edge := pinned(stream, level)
	src := fmt.Sprintf(`
fn %s() -> i64 {
    let mut total: i64 = 0;
    for i in 0..%d {
        if i == %d {
            continue;
        }
        if total > %d * %d {
            break;
        }
        total += i;
    }
    total
}
`, name, stop, skip, stop, skip)
	want := 0
	for i := 0; i < stop; i++ {
		if i == skip {
			continue
		}
		if want > stop*skip {
			break
		}
		want += i
	}
	var edgeCase string
	if edge {
		edgeCase = fmt.Sprintf("    assert!(%s() >= 0);\n", name)
	}
	test := fmt.Sprintf(`
fn test_%s() {
    assert_eq!(%s(), %d);
%s}`, name, name, want, edgeCase)
	return scriptBody{source: src, test: test, pinned: edge}
}

func rsReturnValue(stream *rand.Stream, name, level string) scriptBody {
	threshold := intOperand(stream)
	high := threshold + intOperand(stream)
	edge := pinned(stream, level)
	src := fmt.Sprintf(`
fn %s(n: i64) -> bool {
    if n >= %d {
        return true;
    }
    false
}
`, name, threshold)
	var edgeCase string
	if edge {
		low := intOperand(stream) % threshold
		edgeCase = fmt.Sprintf("    assert!(!%s(%d));\n", name, low)
	}
	test := fmt.Sprintf(`
fn test_%s() {
    assert!(%s(%d));
%s}`, name, name, high, edgeCase)
	return scriptBody{source: src, test: test, pinned: edge}
}

func rsNegate(stream *rand.Stream, name, level string) scriptBody {
	want := intOperand(stream)
	miss := want + 1 + stream.IntN(5)
	edge := pinned(stream, level)
	src := fmt.Sprintf(`
fn %s(n: i64) -> bool {
    n == %d
}
`, name, want)
	var edgeCase string
	if edge {
		edgeCase = fmt.Sprintf("    assert!(!%s(%d));\n", name, miss)
	}
	test := fmt.Sprintf(`
fn test_%s() {
    assert!(%s(%d));
%s}`, name, name, want, edgeCase)
	return scriptBody{source: src, test: test, pinned: edge}
}

func rsCallRemove(stream *rand.Stream, name, level string) scriptBody {
	base := intOperand(stream)
	input := intOperand(stream)
	edge := pinned(stream, level)
	helper := name + "_add"
	src := fmt.Sprintf(`
fn %s(n: i64) -> i64 {
    n + %d
}

fn %s(n: i64) -> i64 {
    %s(n)
}
`, helper, base, name, helper)
	var edgeCase string
	if edge {
		edgeCase = fmt.Sprintf("    assert_eq!(%s(0), %d);\n", name, base)
	}
	test := fmt.Sprintf(`
fn test_%s() {
    assert_eq!(%s(%d), %d);
%s}`, name, name, input, input+base, edgeCase)
	return scriptBody{source: src, test: test, pinned: edge}
}
