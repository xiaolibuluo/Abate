package targetgen

import (
	"fmt"
	"strings"

	"abate/sim/rand"
)

// pythonGen renders the Python target: one target.py whose tests are plain
// functions asserting through assert statements, invoked from main.
type pythonGen struct{}

func (pythonGen) fileName() string { return "target.py" }

func (pythonGen) header() string {
	return "# Code generated by abate targetgen. DO NOT EDIT.\n" +
		"# Deterministic Python mutation-testing target.\n\n"
}

func (pythonGen) footer(testNames []string) string {
	var sb strings.Builder
	sb.WriteString("\ndef main():\n")
	for _, name := range testNames {
		fmt.Fprintf(&sb, "    %s()\n", name)
	}
	sb.WriteString("    print(\"PYTARGET_OK\")\n\n")
	sb.WriteString("if __name__ == \"__main__\":\n    main()\n")
	return sb.String()
}

func (g pythonGen) build(stream *rand.Stream, name, structure, level string) scriptBody {
	switch structure {
	case "arith":
		return pyArith(stream, name, level)
	case "boundary":
		return pyBoundary(stream, name, level)
	case "constant":
		return pyConstant(stream, name, level)
	case "controlflow":
		return pyControlFlow(stream, name, level)
	case "returnvalue":
		return pyReturnValue(stream, name, level)
	case "negate":
		return pyNegate(stream, name, level)
	case "callremove":
		return pyCallRemove(stream, name, level)
	}
	panic("targetgen: unknown py structure " + structure)
}

func (g pythonGen) buildMixed(stream *rand.Stream, name, primary, secondary, level string) scriptBody {
	a := intOperand(stream)
	b := intOperand(stream)
	limit := intOperand(stream)
	x := intOperand(stream)
	y := intOperand(stream)
	edge := pinned(stream, level)
	verdict := pyBool(x*a+y*b < limit)
	src := fmt.Sprintf(`
def %s(x, y):
    """Scale x by %d and y by %d, then compare the sum against %d."""
    total = x * %d + y * %d
    return total < %d
`, name, a, b, limit, a, b, limit)
	var edgeCase string
	if edge {
		edgeCase = fmt.Sprintf("\n    assert %s(%d, 0) == %s\n", name, limit/a, pyBool((limit/a)*a < limit))
	}
	test := fmt.Sprintf(`
def test_%s():
    assert %s(%d, %d) == %s
%s`, name, name, x, y, verdict, edgeCase)
	return scriptBody{source: src, test: test, pinned: edge}
}

// pyBool renders a Go boolean as Python source.
func pyBool(v bool) string {
	if v {
		return "True"
	}
	return "False"
}

func pyArith(stream *rand.Stream, name, level string) scriptBody {
	a := intOperand(stream)
	b := intOperand(stream)
	x := intOperand(stream)
	y := intOperand(stream)
	edge := pinned(stream, level)
	src := fmt.Sprintf("\ndef %s(x, y):\n    return x * %d + y * %d\n", name, a, b)
	var edgeCase string
	if edge {
		edgeCase = fmt.Sprintf("    assert %s(0, 1) == %d\n", name, b)
	}
	test := fmt.Sprintf("\ndef test_%s():\n    assert %s(%d, %d) == %d\n%s", name, name, x, y, x*a+y*b, edgeCase)
	return scriptBody{source: src, test: test, pinned: edge}
}

func pyBoundary(stream *rand.Stream, name, level string) scriptBody {
	limit := intOperand(stream)
	below := 1 + stream.IntN(limit-1)
	above := limit + intOperand(stream)
	edge := pinned(stream, level)
	src := fmt.Sprintf("\ndef %s(n):\n    return n < %d\n", name, limit)
	var edgeCase string
	if edge {
		edgeCase = fmt.Sprintf("    assert %s(%d) is False\n", name, limit)
	}
	test := fmt.Sprintf(`
def test_%s():
    assert %s(%d) is True
    assert %s(%d) is False
%s`, name, name, below, name, above, edgeCase)
	return scriptBody{source: src, test: test, pinned: edge}
}

func pyConstant(stream *rand.Stream, name, level string) scriptBody {
	base := intOperand(stream)
	factor := intOperand(stream)
	offset := intOperand(stream)
	edge := pinned(stream, level)
	src := fmt.Sprintf("\ndef %s():\n    base = %d\n    return base * %d + %d\n", name, base, factor, offset)
	var edgeCase string
	if edge {
		edgeCase = fmt.Sprintf("    assert %s() != 0\n", name)
	}
	test := fmt.Sprintf("\ndef test_%s():\n    assert %s() == %d\n%s", name, name, base*factor+offset, edgeCase)
	return scriptBody{source: src, test: test, pinned: edge}
}

func pyControlFlow(stream *rand.Stream, name, level string) scriptBody {
	stop := 3 + stream.IntN(9)
	skip := 1 + stream.IntN(stop-1)
	edge := pinned(stream, level)
	src := fmt.Sprintf(`
def %s():
    total = 0
    for i in range(%d):
        if i == %d:
            continue
        if total > %d * %d:
            break
        total += i
    return total
`, name, stop, skip, stop, skip)
	want := 0
	for i := 0; i < stop; i++ {
		if i == skip {
			continue
		}
		if want > stop*skip {
			break
		}
		want += i
	}
	var edgeCase string
	if edge {
		edgeCase = fmt.Sprintf("    assert %s() >= 0\n", name)
	}
	test := fmt.Sprintf("\ndef test_%s():\n    assert %s() == %d\n%s", name, name, want, edgeCase)
	return scriptBody{source: src, test: test, pinned: edge}
}

func pyReturnValue(stream *rand.Stream, name, level string) scriptBody {
	threshold := intOperand(stream)
	high := threshold + intOperand(stream)
	edge := pinned(stream, level)
	src := fmt.Sprintf(`
def %s(n):
    if n >= %d:
        return True
    return False
`, name, threshold)
	var edgeCase string
	if edge {
		low := intOperand(stream) % threshold
		edgeCase = fmt.Sprintf("    assert %s(%d) is False\n", name, low)
	}
	test := fmt.Sprintf("\ndef test_%s():\n    assert %s(%d) is True\n%s", name, name, high, edgeCase)
	return scriptBody{source: src, test: test, pinned: edge}
}

func pyNegate(stream *rand.Stream, name, level string) scriptBody {
	want := intOperand(stream)
	miss := want + 1 + stream.IntN(5)
	edge := pinned(stream, level)
	src := fmt.Sprintf("\ndef %s(n):\n    return n == %d\n", name, want)
	var edgeCase string
	if edge {
		edgeCase = fmt.Sprintf("    assert %s(%d) is False\n", name, miss)
	}
	test := fmt.Sprintf("\ndef test_%s():\n    assert %s(%d) is True\n%s", name, name, want, edgeCase)
	return scriptBody{source: src, test: test, pinned: edge}
}

func pyCallRemove(stream *rand.Stream, name, level string) scriptBody {
	base := intOperand(stream)
	input := intOperand(stream)
	edge := pinned(stream, level)
	helper := name + "_add"
	src := fmt.Sprintf("\ndef %s(n):\n    return %s(n)\n\ndef %s(n):\n    return n + %d\n", name, helper, helper, base)
	var edgeCase string
	if edge {
		edgeCase = fmt.Sprintf("    assert %s(0) == %d\n", name, base)
	}
	test := fmt.Sprintf("\ndef test_%s():\n    assert %s(%d) == %d\n%s", name, name, input, input+base, edgeCase)
	return scriptBody{source: src, test: test, pinned: edge}
}
