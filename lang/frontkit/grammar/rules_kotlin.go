package grammar

import "abate/lang/air"

// kotlinRules maps the tree-sitter-kotlin constructs onto the AIR node model.
//
// Kotlin folds statements into expressions, so the upstream inventory mixes
// declaration and expression families; the mapping keeps the AIR family of
// each construct explicit.
func kotlinRules() []MappingRule {
	return []MappingRule{
		exact("kt.file", air.KindPackage, "source_file"),
		exact("kt.package", air.KindPackage, "package_header"),
		exact("kt.import", air.KindImport, "import_header", "wildcard_import"),
		exact("kt.import-list", air.KindKtImportList, "import_list"),
		exact("kt.import-alias", air.KindKtImportAlias, "import_alias"),
		exact("kt.class", air.KindClassDecl, "class_declaration"),
		exact("kt.object", air.KindClassDecl, "object_declaration"),
		exact("kt.companion", air.KindKtCompanion, "companion_object"),
		exact("kt.func", air.KindFuncDecl, "function_declaration"),
		exact("kt.accessor", air.KindKtAccessor, "getter", "setter"),
		exact("kt.secondary-ctor", air.KindKtSecondaryCtor, "secondary_constructor"),
		exact("kt.annotation", air.KindAnnotationDecl, "annotation",
			"file_annotation"),
		exact("kt.type-alias", air.KindTypeDecl, "type_alias"),
		exact("kt.var", air.KindVarDecl, "variable_declaration"),
		degraded("kt.multi-var", air.KindVarDecl,
			"多变量声明降级为变量声明节点", "multi_variable_declaration"),
		exact("kt.property", air.KindKtProperty, "property_declaration"),
		degraded("kt.property-delegate", air.KindRegion,
			"属性委托无独立节点，降级为区域节点", "property_delegate"),

		exact("kt.if", air.KindIf, "if_expression"),
		degraded("kt.for", air.KindRangeFor,
			"Kotlin for 循环遍历可迭代对象，没有 C 风格计数循环，降级为范围循环节点",
			"for_statement"),
		exact("kt.while", air.KindWhile, "while_statement"),
		exact("kt.do", air.KindDoWhile, "do_while_statement"),
		exact("kt.when", air.KindMatch, "when_expression"),
		exact("kt.when-subject", air.KindMatchExpr, "when_subject"),
		exact("kt.when-entry", air.KindKtWhenEntry, "when_entry"),
		degraded("kt.when-condition", air.KindRegion,
			"when 条件无独立节点，降级为区域节点", "when_condition"),
		exact("kt.try", air.KindTry, "try_expression"),
		exact("kt.catch", air.KindCatch, "catch_block"),
		exact("kt.finally", air.KindFinally, "finally_block"),
		degraded("kt.jump", air.KindBranch,
			"跳转表达式降级为分支节点", "jump_expression"),
		degraded("kt.label", air.KindLabel, "全语料零产出，回退 degraded 避免 exact 分母虚增", "label"),
		exact("kt.block", air.KindBlock, "function_body"),
		exact("kt.control-body", air.KindKtControlBody, "control_structure_body"),

		exact("kt.assign", air.KindAssign, "assignment"),
		exact("kt.additive", air.KindBinary, "additive_expression"),
		exact("kt.multiplicative", air.KindBinary, "multiplicative_expression"),
		exact("kt.comparison", air.KindBinary, "comparison_expression"),
		exact("kt.equality", air.KindBinary, "equality_expression"),
		exact("kt.conjunction", air.KindBinary, "conjunction_expression"),
		exact("kt.disjunction", air.KindBinary, "disjunction_expression"),
		exact("kt.prefix", air.KindUnary, "prefix_expression"),
		degraded("kt.postfix", air.KindUnary,
			"后缀表达式降级为一元运算节点", "postfix_expression"),
		exact("kt.call", air.KindCall, "call_expression"),
		degraded("kt.infix-call", air.KindCall,
			"中缀调用降级为调用节点", "infix_expression"),
		degraded("kt.ctor-call", air.KindCall,
			"构造调用降级为调用节点", "constructor_invocation"),
		exact("kt.ctor-delegation", air.KindKtCtorDelegation,
			"constructor_delegation_call"),
		exact("kt.index", air.KindIndex, "indexing_expression"),
		exact("kt.navigation", air.KindSelector, "navigation_expression"),
		exact("kt.this-expr", air.KindKtThis, "this_expression"),
		exact("kt.super-expr", air.KindKtSuper, "super_expression"),
		exact("kt.callable-ref", air.KindKtCallableRef, "callable_reference"),
		degraded("kt.ternary", air.KindTernary, "全语料零产出，回退 degraded 避免 exact 分母虚增", "elvis_expression"),
		exact("kt.lambda", air.KindLambda, "lambda_literal"),
		degraded("kt.annotated-lambda", air.KindLambda,
			"带注解 lambda 降级为 lambda 节点", "annotated_lambda"),
		exact("kt.anonymous-func", air.KindLambda, "anonymous_function"),
		degraded("kt.anonymous-init", air.KindCompositeLit,
			"匿名初始化块降级为复合字面量节点", "anonymous_initializer"),
		degraded("kt.collection", air.KindCompositeLit, "全语料零产出，回退 degraded 避免 exact 分母虚增", "collection_literal"),
		degraded("kt.object-literal", air.KindCompositeLit, "全语料零产出，回退 degraded 避免 exact 分母虚增", "object_literal"),
		degraded("kt.spread", air.KindSpread, "全语料零产出，回退 degraded 避免 exact 分母虚增", "spread_expression"),
		degraded("kt.as", air.KindCast,
			"as 表达式降级为类型断言节点", "as_expression"),
		exact("kt.type-test", air.KindTypeAssert, "type_test"),
		degraded("kt.check", air.KindRegion,
			"check 表达式无独立节点，降级为区域节点", "check_expression"),
		exact("kt.interpolated", air.KindKtInterp, "interpolated_expression"),
		degraded("kt.interpolated-ident", air.KindRegion,
			"模板标识符片段无独立节点，降级为区域节点",
			"interpolated_identifier"),
		degraded("kt.paren-expr", air.KindRegion,
			"括号表达式无独立节点，降级为区域节点", "parenthesized_expression"),
		degraded("kt.assignable", air.KindRegion,
			"可赋值表达式标记无独立节点，降级为区域节点",
			"directly_assignable_expression"),
		degraded("kt.range", air.KindRangeFor,
			"区间表达式降级为范围循环节点", "range_expression"),
		degraded("kt.range-test", air.KindRegion,
			"区间判定无独立节点，降级为区域节点", "range_test"),

		degraded("kt.named-type", air.KindNamed, "全语料零产出，回退 degraded 避免 exact 分母虚增", "user_type", "type_identifier"),
		exact("kt.nullable-type", air.KindOptional, "nullable_type"),
		degraded("kt.not-null-type", air.KindNamed,
			"非空类型降级为命名类型节点", "not_nullable_type"),
		degraded("kt.fn-type", air.KindFuncType, "全语料零产出，回退 degraded 避免 exact 分母虚增", "function_type"),
		degraded("kt.fn-type-params", air.KindRegion,
			"函数类型形参列表无独立节点，降级为区域节点",
			"function_type_parameters", "function_value_parameters"),
		degraded("kt.paren-type", air.KindNamed,
			"带括号类型降级为命名类型节点",
			"parenthesized_type", "parenthesized_user_type"),
		degraded("kt.type-args", air.KindGenericInst,
			"类型实参列表降级为泛型实例节点",
			"type_arguments", "type_projection"),
		degraded("kt.generic-param", air.KindGenericParam, "全语料零产出，回退 degraded 避免 exact 分母虚增", "type_parameter"),
		degraded("kt.type-params", air.KindRegion,
			"类型形参列表无独立节点，降级为区域节点",
			"type_parameters", "type_parameter_modifiers",
			"type_projection_modifiers", "type_constraints", "type_constraint"),
		degraded("kt.type-modifiers", air.KindAttribute,
			"类型修饰符降级为属性节点", "type_modifiers"),
		degraded("kt.modifiers", air.KindAttribute,
			"声明修饰符降级为属性节点",
			"modifiers", "class_modifier", "member_modifier",
			"inheritance_modifier", "parameter_modifier", "parameter_modifiers",
			"property_modifier", "function_modifier", "platform_modifier",
			"reification_modifier", "variance_modifier", "visibility_modifier"),
		degraded("kt.class-parameter", air.KindRegion,
			"主构造函数形参无独立节点，降级为区域节点",
			"class_parameter", "parameter", "parameter_with_optional_type"),
		degraded("kt.lambda-params", air.KindRegion,
			"lambda 形参无独立节点，降级为区域节点", "lambda_parameters"),
		degraded("kt.primary-ctor", air.KindRegion,
			"主构造函数无独立节点，降级为区域节点", "primary_constructor"),
		degraded("kt.class-body", air.KindRegion,
			"类体无独立节点，降级为区域节点", "class_body"),
		degraded("kt.enum-body", air.KindRegion,
			"枚举体无独立节点，降级为区域节点", "enum_class_body"),
		degraded("kt.enum-entry", air.KindEnumDecl,
			"枚举条目降级为枚举声明节点", "enum_entry"),
		degraded("kt.delegation", air.KindRegion,
			"委派规格无独立节点，降级为区域节点",
			"delegation_specifier", "explicit_delegation"),
		degraded("kt.binding-pattern", air.KindRegion,
			"绑定模式无独立节点，降级为区域节点", "binding_pattern_kind"),
		degraded("kt.statements", air.KindRegion,
			"语句列表无独立节点，降级为区域节点", "statements"),
		degraded("kt.value-args", air.KindRegion,
			"实参列表在 AIR 无独立节点，降级为区域节点",
			"value_argument", "value_arguments"),
		degraded("kt.suffix", air.KindRegion,
			"调用与导航后缀无独立节点，降级为区域节点",
			"call_suffix", "navigation_suffix", "indexing_suffix"),
		degraded("kt.use-site", air.KindRegion,
			"use-site 目标无独立节点，降级为区域节点", "use_site_target"),

		exact("kt.number", air.KindNumLit, "long_literal", "integer_literal",
			"unsigned_literal", "real_literal", "bin_literal", "hex_literal"),
		exact("kt.string", air.KindStrLit, "string_literal"),
		exact("kt.string-part", air.KindKtStringFrag, "string_content"),
		exact("kt.char", air.KindCharLit, "character_literal"),
		degraded("kt.char-escape", air.KindCharLit,
			"字符转义并入字符节点", "character_escape_seq"),
		exact("kt.bool", air.KindBoolLit, "boolean_literal"),
		exact("kt.comment", air.KindComment, "line_comment", "multiline_comment"),
		degraded("kt.shebang", air.KindDirective, "全语料零产出，回退 degraded 避免 exact 分母虚增", "shebang_line"),
		degraded("kt.simple-identifier", air.KindIdent,
			"简单标识符并入标识符节点", "simple_identifier"),
	}
}
