package grammar

import "abate/lang/air"

// javascriptRules maps the tree-sitter-javascript constructs onto the AIR
// node model.
//
// The upstream grammar also carries the TypeScript and JSX extensions, so
// every entry of the concrete node inventory is listed exactly once.
func javascriptRules() []MappingRule {
	return []MappingRule{
		exact("js.program", air.KindPackage, "program"),
		exact("js.import", air.KindImport, "import_statement", "import_clause",
			"import_specifier", "import", "named_imports", "namespace_import",
			"import_attribute"),
		exact("js.export", air.KindJsExport,
			"export_statement", "export_clause", "export_specifier",
			"namespace_export"),
		exact("js.func", air.KindFuncDecl, "function_declaration"),
		exact("js.generator-func-decl", air.KindJsGeneratorFnDecl,
			"generator_function_declaration"),
		exact("js.func-lit", air.KindFuncLit, "function_expression"),
		exact("js.generator-func", air.KindJsGeneratorFn, "generator_function"),
		exact("js.arrow", air.KindArrow, "arrow_function"),
		exact("js.class", air.KindClassDecl, "class_declaration"),
		exact("js.class-expr", air.KindJsClassExpr, "class"),
		exact("js.class-body", air.KindJsClassBody, "class_body"),
		exact("js.class-heritage", air.KindJsClassHeritage, "class_heritage"),
		exact("js.static-block", air.KindJsStaticBlock, "class_static_block"),
		exact("js.method", air.KindMethodDecl, "method_definition"),
		degraded("js.field-def", air.KindField,
			"字段定义降级为字段节点", "field_definition"),
		exact("js.computed-name", air.KindJsComputedName, "computed_property_name"),
		exact("js.decorator", air.KindDecorator, "decorator"),

		exact("js.expr-stmt", air.KindExprStmt, "expression_statement"),
		exact("js.if", air.KindIf, "if_statement"),
		exact("js.else", air.KindIf, "else_clause"),
		exact("js.for", air.KindFor, "for_statement"),
		exact("js.for-in", air.KindRangeFor, "for_in_statement"),
		exact("js.while", air.KindWhile, "while_statement"),
		exact("js.do", air.KindDoWhile, "do_statement"),
		exact("js.switch", air.KindSwitch, "switch_statement"),
		exact("js.switch-body", air.KindJsSwitchBody, "switch_body"),
		exact("js.case", air.KindCase, "switch_case"),
		exact("js.switch-default", air.KindJsSwitchDefault, "switch_default"),
		exact("js.try", air.KindTry, "try_statement"),
		exact("js.catch", air.KindCatch, "catch_clause"),
		exact("js.finally", air.KindFinally, "finally_clause"),
		exact("js.throw", air.KindThrow, "throw_statement"),
		exact("js.return", air.KindReturn, "return_statement"),
		exact("js.branch", air.KindBranch, "break_statement", "continue_statement"),
		degraded("js.label", air.KindLabel, "全语料零产出，回退 degraded 避免 exact 分母虚增", "labeled_statement"),
		exact("js.with", air.KindWith, "with_statement"),
		exact("js.debugger", air.KindJsDebugger, "debugger_statement"),
		degraded("js.empty-stmt", air.KindJsEmptyStmt,
			"空语句降级为独立空语句节点", "empty_statement"),
		exact("js.block", air.KindBlock, "statement_block"),

		exact("js.var", air.KindVarDecl, "variable_declaration"),
		exact("js.lexical-decl", air.KindJsLexicalDecl, "lexical_declaration"),
		exact("js.using-decl", air.KindJsUsingDecl, "using_declaration"),
		exact("js.declarator", air.KindJsDeclarator, "variable_declarator"),

		exact("js.assign", air.KindAssign, "assignment_expression"),
		exact("js.assign-augmented", air.KindJsAugAssign,
			"augmented_assignment_expression"),
		exact("js.binary", air.KindBinary, "binary_expression"),
		exact("js.unary", air.KindUnary, "unary_expression"),
		exact("js.incdec", air.KindJsIncDec, "update_expression"),
		exact("js.call", air.KindCall, "call_expression"),
		exact("js.new", air.KindJsNew, "new_expression"),
		exact("js.member", air.KindField, "member_expression"),
		degraded("js.optional-chain", air.KindField,
			"可选链降级为字段节点", "optional_chain"),
		exact("js.index", air.KindIndex, "subscript_expression"),
		exact("js.paren-expr", air.KindJsParenExpr, "parenthesized_expression"),
		exact("js.sequence", air.KindJsSequence, "sequence_expression"),
		exact("js.ternary", air.KindTernary, "ternary_expression"),
		exact("js.await", air.KindAwait, "await_expression"),
		exact("js.yield", air.KindJsYield, "yield_expression"),
		exact("js.array", air.KindCompositeLit, "array"),
		exact("js.object", air.KindCompositeLit, "object"),
		exact("js.pair", air.KindJsPair, "pair"),
		exact("js.spread", air.KindSpread, "spread_element"),
		exact("js.rest-pattern", air.KindJsRestPattern, "rest_pattern"),
		exact("js.assign-pattern", air.KindJsAssignPattern,
			"assignment_pattern"),
		exact("js.object-assign-pattern", air.KindJsObjectAssignPat,
			"object_assignment_pattern"),
		exact("js.pair-pattern", air.KindJsPairPattern, "pair_pattern"),
		exact("js.object-pattern", air.KindJsObjectPattern,
			"object_pattern"),
		exact("js.array-pattern", air.KindJsArrayPattern,
			"array_pattern"),

		exact("js.template", air.KindStrLit, "template_string"),
		exact("js.template-substitution", air.KindJsTemplateSub, "template_substitution"),
		exact("js.string", air.KindStrLit, "string"),
		exact("js.string-part", air.KindJsStringPart,
			"string_fragment", "escape_sequence", "html_character_reference"),
		exact("js.regex", air.KindJsRegex,
			"regex", "regex_pattern", "regex_flags"),
		exact("js.number", air.KindNumLit, "number"),
		exact("js.ident-family", air.KindJsPropertyIdent,
			"property_identifier", "private_property_identifier",
			"shorthand_property_identifier",
			"shorthand_property_identifier_pattern", "statement_identifier"),
		exact("js.this-super", air.KindJsThisSuper, "this", "super"),
		exact("js.meta-property", air.KindJsMetaProperty, "meta_property"),
		exact("js.arguments", air.KindJsArguments, "arguments"),
		exact("js.formal-parameters", air.KindJsFormalParams, "formal_parameters"),
		exact("js.jsx", air.KindJsJsx,
			"jsx_element", "jsx_opening_element", "jsx_closing_element",
			"jsx_self_closing_element", "jsx_attribute", "jsx_expression",
			"jsx_namespace_name", "jsx_text"),
		exact("js.html-comment", air.KindComment, "html_comment"),
		exact("js.hash-bang", air.KindDirective, "hash_bang_line"),
	}
}
