package grammar

import "abate/lang/air"

// javascriptRules maps the tree-sitter-javascript constructs onto the AIR
// node model.
//
// The upstream grammar also carries the TypeScript and JSX extensions, so
// every entry of the concrete node inventory is listed exactly once.
func javascriptRules() []MappingRule {
	return []MappingRule{
		exact("js.program", air.KindPackage, "program"),
		exact("js.import", air.KindImport, "import_statement", "import_clause",
			"import_specifier", "import", "named_imports", "namespace_import",
			"import_attribute"),
		degraded("js.export", air.KindModuleDecl,
			"导出声明降级为模块声明节点",
			"export_statement", "export_clause", "export_specifier",
			"namespace_export"),
		exact("js.func", air.KindFuncDecl, "function_declaration"),
		degraded("js.generator-func-decl", air.KindFuncDecl,
			"生成器声明降级为函数声明节点", "generator_function_declaration"),
		exact("js.func-lit", air.KindFuncLit, "function_expression"),
		degraded("js.generator-func", air.KindFuncLit,
			"生成器函数表达式降级为函数字面量节点", "generator_function"),
		exact("js.arrow", air.KindArrow, "arrow_function"),
		exact("js.class", air.KindClassDecl, "class_declaration"),
		degraded("js.class-expr", air.KindClassDecl,
			"类表达式降级为类声明节点", "class"),
		degraded("js.class-body", air.KindRegion,
			"类体无独立节点，降级为区域节点", "class_body"),
		degraded("js.class-heritage", air.KindRegion,
			"基类列表无独立节点，降级为区域节点", "class_heritage"),
		degraded("js.static-block", air.KindBlock,
			"静态初始化块降级为块节点", "class_static_block"),
		exact("js.method", air.KindMethodDecl, "method_definition"),
		degraded("js.field-def", air.KindField,
			"字段定义降级为字段节点", "field_definition"),
		degraded("js.computed-name", air.KindRegion,
			"计算属性名无独立节点，降级为区域节点", "computed_property_name"),
		exact("js.decorator", air.KindDecorator, "decorator"),

		exact("js.expr-stmt", air.KindExprStmt, "expression_statement"),
		exact("js.if", air.KindIf, "if_statement"),
		exact("js.else", air.KindIf, "else_clause"),
		exact("js.for", air.KindFor, "for_statement"),
		exact("js.for-in", air.KindRangeFor, "for_in_statement"),
		exact("js.while", air.KindWhile, "while_statement"),
		exact("js.do", air.KindDoWhile, "do_statement"),
		exact("js.switch", air.KindSwitch, "switch_statement"),
		degraded("js.switch-body", air.KindRegion,
			"switch 体无独立节点，降级为区域节点", "switch_body"),
		exact("js.case", air.KindCase, "switch_case"),
		degraded("js.switch-default", air.KindCase,
			"switch 默认分支降级为分支节点", "switch_default"),
		exact("js.try", air.KindTry, "try_statement"),
		exact("js.catch", air.KindCatch, "catch_clause"),
		exact("js.finally", air.KindFinally, "finally_clause"),
		exact("js.throw", air.KindThrow, "throw_statement"),
		exact("js.return", air.KindReturn, "return_statement"),
		exact("js.branch", air.KindBranch, "break_statement", "continue_statement"),
		degraded("js.label", air.KindLabel, "全语料零产出，回退 degraded 避免 exact 分母虚增", "labeled_statement"),
		exact("js.with", air.KindWith, "with_statement"),
		degraded("js.debugger", air.KindRegion,
			"debugger 语句降级为区域节点", "debugger_statement"),
		degraded("js.empty-stmt", air.KindRegion,
			"空语句降级为区域节点", "empty_statement"),
		exact("js.block", air.KindBlock, "statement_block"),

		exact("js.var", air.KindVarDecl, "variable_declaration"),
		degraded("js.lexical-decl", air.KindVarDecl,
			"词法声明按 let/const 区分降级为变量声明与常量声明节点",
			"lexical_declaration"),
		degraded("js.using-decl", air.KindVarDecl,
			"using 声明降级为变量声明节点", "using_declaration"),
		degraded("js.declarator", air.KindRegion,
			"变量声明符无独立节点，降级为区域节点", "variable_declarator"),

		exact("js.assign", air.KindAssign, "assignment_expression"),
		degraded("js.assign-augmented", air.KindAssign,
			"复合赋值降级为赋值节点", "augmented_assignment_expression"),
		exact("js.binary", air.KindBinary, "binary_expression"),
		exact("js.unary", air.KindUnary, "unary_expression"),
		degraded("js.incdec", air.KindIncDec, "全语料零产出，回退 degraded 避免 exact 分母虚增", "update_expression"),
		exact("js.call", air.KindCall, "call_expression"),
		degraded("js.new", air.KindCall,
			"new 表达式降级为调用节点", "new_expression"),
		exact("js.member", air.KindField, "member_expression"),
		degraded("js.optional-chain", air.KindField,
			"可选链降级为字段节点", "optional_chain"),
		exact("js.index", air.KindIndex, "subscript_expression"),
		degraded("js.paren-expr", air.KindRegion,
			"括号表达式无独立节点，降级为区域节点", "parenthesized_expression"),
		degraded("js.sequence", air.KindTuple,
			"逗号表达式降级为元组节点", "sequence_expression"),
		exact("js.ternary", air.KindTernary, "ternary_expression"),
		exact("js.await", air.KindAwait, "await_expression"),
		degraded("js.yield", air.KindUnary,
			"yield 表达式降级为一元运算节点", "yield_expression"),
		exact("js.array", air.KindCompositeLit, "array"),
		exact("js.object", air.KindCompositeLit, "object"),
		degraded("js.pair", air.KindAssign,
			"对象字面量键值对降级为赋值节点", "pair"),
		exact("js.spread", air.KindSpread, "spread_element"),
		degraded("js.rest-pattern", air.KindSpread,
			"剩余参数模式降级为展开节点", "rest_pattern"),
		degraded("js.assign-pattern", air.KindAssign,
			"解构赋值模式降级为赋值节点", "assignment_pattern"),
		degraded("js.object-assign-pattern", air.KindAssign,
			"对象解构模式降级为赋值节点", "object_assignment_pattern"),
		degraded("js.pair-pattern", air.KindAssign,
			"解构键值模式降级为赋值节点", "pair_pattern"),
		degraded("js.object-pattern", air.KindRegion,
			"解构模式在 AIR 无独立节点，降级为区域节点", "object_pattern"),
		degraded("js.array-pattern", air.KindRegion,
			"解构模式在 AIR 无独立节点，降级为区域节点", "array_pattern"),

		exact("js.template", air.KindStrLit, "template_string"),
		degraded("js.template-substitution", air.KindRegion,
			"模板插值降级为区域节点", "template_substitution"),
		exact("js.string", air.KindStrLit, "string"),
		degraded("js.string-part", air.KindStrLit,
			"字符串片段并入字符串节点", "string_fragment", "escape_sequence",
			"html_character_reference"),
		degraded("js.regex", air.KindStrLit,
			"正则字面量降级为字符串节点", "regex", "regex_pattern", "regex_flags"),
		exact("js.number", air.KindNumLit, "number"),
		degraded("js.ident-family", air.KindIdent,
			"属性名与语句标签并入标识符节点",
			"property_identifier", "private_property_identifier",
			"shorthand_property_identifier",
			"shorthand_property_identifier_pattern", "statement_identifier"),
		degraded("js.this-super", air.KindIdent,
			"this/super 降级为标识符节点", "this", "super"),
		degraded("js.meta-property", air.KindRegion,
			"new.target 元属性无独立节点，降级为区域节点", "meta_property"),
		degraded("js.arguments", air.KindRegion,
			"实参列表在 AIR 无独立节点，降级为区域节点", "arguments"),
		degraded("js.formal-parameters", air.KindRegion,
			"形参列表在 AIR 无独立节点，降级为区域节点", "formal_parameters"),
		degraded("js.jsx", air.KindCompositeLit,
			"JSX 元素降级为复合字面量节点",
			"jsx_element", "jsx_opening_element", "jsx_closing_element",
			"jsx_self_closing_element", "jsx_attribute", "jsx_expression",
			"jsx_namespace_name", "jsx_text"),
		exact("js.html-comment", air.KindComment, "html_comment"),
		exact("js.hash-bang", air.KindDirective, "hash_bang_line"),
	}
}
