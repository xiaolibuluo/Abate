package grammar

import "abate/lang/air"

// rustRules maps the tree-sitter-rust constructs onto the AIR node model.
//
// Rust patterns, lifetimes and macro grammars have no AIR counterpart, so
// they are lowered onto region nodes with the reason recorded.
