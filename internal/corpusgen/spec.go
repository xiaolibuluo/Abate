package corpusgen

// ManifestRefs is the first-party provenance shared by every generated entry.
// Every field is authored by this project; no third-party identifier appears.
type ManifestRefs struct {
	Project         string
	UpstreamURL     string
	Commit          string
	SPDX            string
	EvidenceRelPath string
	Source          string
	ConstructTags   []string
}

// DedicationRelPath is the CC0 waiver checked in beside the generated corpus.
const DedicationRelPath = "SELF_RESEARCHED_CORPUS_DEDICATION.md"

// SelfResearchedRefs returns the immutable provenance of the corpus bytes.
func SelfResearchedRefs() ManifestRefs {
	return ManifestRefs{
		Project:         "Abate Self-Research Corpus",
		UpstreamURL:     "",
		Commit:          "self-researched-v1",
		SPDX:            "CC0-1.0",
		EvidenceRelPath: DedicationRelPath,
		Source:          "self_researched",
	}
}

