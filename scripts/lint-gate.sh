#!/usr/bin/env bash
# =============================================================================
# Abate 项目 CI/CD 严格门禁
# 任何一环失败立即 exit 1，并明确打印触发的规则条例。
# 门禁链：gofmt -> go vet(全量) -> golangci-lint(全量 linter) -> test(-race) -> build
# =============================================================================
set -uo pipefail

RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
NC='\033[0m'

FAILED=0
REPORT=""

banner() {
  echo -e "${YELLOW}=================================================================${NC}"
  echo -e "${YELLOW}  $1${NC}"
  echo -e "${YELLOW}=================================================================${NC}"
}

fail() {
  FAILED=1
  REPORT="${REPORT}\n  [FAIL] $1"
  echo -e "${RED}[FAIL] $1${NC}"
}

pass() {
  echo -e "${GREEN}[PASS] $1${NC}"
}

cd "$(dirname "$0")/.." || exit 2
export PATH="$PATH:$(go env GOPATH)/bin"

banner "Abate CI Gate - Start"

# -----------------------------------------------------------------------------
# 0. 版权头门禁（XCU-GOV）：统一版权头 + 小黎的部落水印，缺失即 FAIL。
# -----------------------------------------------------------------------------
echo ">>> [0] 版权头门禁 (header-check)"
if ! bash scripts/header-check.sh; then
  fail "header-check: 版权头缺失（规则: 架构 §10 强制版权头 + 数字水印）"
else
  pass "header-check: 版权头齐全"
fi

# -----------------------------------------------------------------------------
# 1. 代码风格门禁（XCU-CI 自定义）：单文件 ≤300 行 / 一类一个文件 / 无占位注释。
# -----------------------------------------------------------------------------
echo ">>> [1] 代码风格门禁 (style-check)"
if ! bash scripts/style-check.sh; then
  fail "style-check: 违反文件长度/一类一个文件/占位注释规则"
else
  pass "style-check: 风格规则通过"
fi

# -----------------------------------------------------------------------------
# 2. 许可证门禁（供应链红线）：禁止 GPL 系依赖，非 Go 源码不接入。
# -----------------------------------------------------------------------------
echo ">>> [2] 许可证门禁 (license-check)"
if ! bash scripts/license-check.sh; then
  fail "license-check: 命中 GPL 系依赖或缺失第三方清单（红线：禁止 GPL）"
else
  pass "license-check: 许可证合规"
fi

# -----------------------------------------------------------------------------
# 3. gofmt / gofumpt：代码格式化（CodeReviewComments - Gofmt）。
# -----------------------------------------------------------------------------
echo ">>> [3] gofmt 格式化检查"
# 第三方源码（vendor/third_party）保持上游原样，不属于本仓库格式化范围。
UNFMT=$(gofmt -l . 2>/dev/null | grep -vE '^(vendor|third_party)/' | grep -v '^$' || true)
if [ -n "$UNFMT" ]; then
  fail "gofmt: 以下文件未格式化（规则: CodeReviewComments#Gofmt - 必须先 gofmt）\n$UNFMT"
else
  pass "gofmt: 全部文件已格式化"
fi

# -----------------------------------------------------------------------------
# 4. go vet：官方全部分析器全量。
# -----------------------------------------------------------------------------
echo ">>> [4] go vet 官方全部分析器"
if ! go vet ./... 2>&1; then
  fail "go vet: 命中官方分析器规则（规则: pkg.go.dev/cmd/vet 全量分析器）"
else
  pass "go vet: 分析器全部通过"
fi

# -----------------------------------------------------------------------------
# 5. golangci-lint v2：全量 linter，issues-exit-code=1 任何命中即失败。
#    规则条例见 .golangci.yml，每条 linter 均对应官方/社区门禁条款。
# -----------------------------------------------------------------------------
echo ">>> [5] golangci-lint v2 全量 linter 门禁"
if ! golangci-lint run --issues-exit-code=1 --timeout=10m ./... 2>&1; then
  fail "golangci-lint: 命中门禁规则（规则: .golangci.yml 全量 linter，见上方输出每条 rule id）"
else
  pass "golangci-lint: 全量 linter 通过"
fi

# -----------------------------------------------------------------------------
# 5b. 精准魔法常量门禁（替代 revive add-constant）：仅抓 0x100+ / 10000+ 的
#     非测试、非复合字面量数据表的真实魔法常量，命中即要求具名。
# -----------------------------------------------------------------------------
echo ">>> [5b] 精准魔法常量门禁 (constant-lint)"
if ! bash scripts/constant-lint.sh; then
  fail "constant-lint: 发现无名魔法常量（规则: scripts/constant-lint.sh 高信噪比扫描）"
else
  pass "constant-lint: 魔法常量门禁通过"
fi

# -----------------------------------------------------------------------------
# 6. 单元测试 + 竞态检测：杜绝未测试代码与并发缺陷。
# -----------------------------------------------------------------------------
echo ">>> [6] go test -race -count=1"
if ! go test -race -count=1 ./... 2>&1; then
  fail "go test: 测试失败或存在数据竞态（规则: 所有提交必须通过 -race 测试）"
else
  pass "go test: 测试与竞态检测通过"
fi

# -----------------------------------------------------------------------------
# 7. 覆盖率门禁（XCU-TST / 用户规则：混沌 & 变异测试必须覆盖）。
# -----------------------------------------------------------------------------
echo ">>> [7] 覆盖率门禁 (coverage-gate)"
if ! bash scripts/coverage-gate.sh; then
  fail "coverage-gate: 覆盖率低于门槛或内核包缺混沌/变异测试"
else
  pass "coverage-gate: 覆盖率达标"
fi

# -----------------------------------------------------------------------------
# 8. 构建验证：必须可编译，杜绝半成品提交。
# -----------------------------------------------------------------------------
echo ">>> [8] go build 编译验证"
if ! go build ./... 2>&1; then
  fail "go build: 编译失败（规则: 提交代码必须可编译，禁止桩/半成品）"
else
  pass "go build: 编译通过"
fi

# -----------------------------------------------------------------------------
# 9. 第十段 E2E 闭环门禁（T01 骨架）：S1/S2 可跑，S3-S7 依赖 T04 就绪。
# -----------------------------------------------------------------------------
echo ">>> [9] E2E 闭环门禁 (ci/gate_e2e.sh)"
if ! bash ci/gate_e2e.sh; then
  fail "gate_e2e: 第十段闭环未通过（规则: ci/gate_e2e.sh S1-S7，红灯起点不得伪绿）"
else
  pass "gate_e2e: 第十段闭环通过"
fi

# -----------------------------------------------------------------------------
# 门禁结论
# -----------------------------------------------------------------------------
echo ""
if [ "$FAILED" -ne 0 ]; then
  banner "CI GATE: FAILED - 触发规则条例如下"
  echo -e "${RED}${REPORT}${NC}"
  echo -e "${RED}请修复以上规则违规后重新提交。规则全集：.golangci.yml + pkg.go.dev/cmd/vet${NC}"
  exit 1
fi

banner "CI GATE: PASSED - 全部门禁规则通过"
exit 0
